export interface GlyphBox {
  /** Scale from the 24-box to disc units. */
  k: number
  /** The box's top-left corner in disc units. */
  x0: number
  y0: number
}

/** Where a glyph's 24-box lands on the 32-unit disc: centred, spanning `span` of the diameter, then nudged. */
export function glyphBox({ span, dx, dy }: MarkGlyph): GlyphBox {
  const side = 32 * span
  return { k: side / 24, x0: (32 - side) / 2 + dx, y0: (32 - side) / 2 + dy }
}

/** The SVG `transform` for a glyph's path on the disc. */
export function glyphTransform(glyph: MarkGlyph): string {
  const { k, x0, y0 } = glyphBox(glyph)
  return `translate(${x0} ${y0}) scale(${k})`
}

